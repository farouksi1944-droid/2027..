import type { DayPlan, ScheduleBlock, SpacedStage, SubjectId } from '../types/study';
import { TERM1_LESSONS } from './curriculum';

const lessonMap = new Map(TERM1_LESSONS.map((l) => [l.id, l]));

function studyBlock(
  id: string,
  date: string,
  startTime: string,
  endTime: string,
  durationLabel: string,
  lessonOrIds: string | string[],
  stage: SpacedStage,
  customSubtitle?: string,
  customTitle?: string
): ScheduleBlock {
  const lessonIds = Array.isArray(lessonOrIds) ? lessonOrIds : [lessonOrIds];
  const primaryLesson = lessonMap.get(lessonIds[0]);
  const stageLabels: Record<SpacedStage, string> = {
    S0: 'فهم وبناء الملخص من البداية + حل التمارين',
    R1: 'تكرار متباعد +1 يوم: استرجاع نشط بدون كراس',
    R2: 'تكرار متباعد +3 أيام: حل تمارين بكالوريا',
    R3: 'تكرار متباعد نهائي: تثبيت شامل وموضوع نموذجي',
  };

  const xpMap: Record<SpacedStage, number> = {
    S0: 60,
    R1: 35,
    R2: 50,
    R3: 70,
  };

  return {
    id,
    date,
    startTime,
    endTime,
    durationLabel,
    type: stage === 'S0' ? 'study_new' : 'spaced_review',
    title: customTitle ?? (primaryLesson ? primaryLesson.title : lessonIds[0]),
    subtitle: customSubtitle ?? stageLabels[stage],
    subjectId: primaryLesson?.subjectId as SubjectId | undefined,
    lessonId: lessonIds[0],
    lessonIds,
    stage,
    xpReward: xpMap[stage] * lessonIds.length,
  };
}

